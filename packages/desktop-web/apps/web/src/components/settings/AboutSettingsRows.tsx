/**
 * myna's About rows for the gateway's public address (NEOLIX_PUBLIC_URL) and
 * the statusLine command another computer runs to read this host's usage.
 */
export function AboutRemoteAccessRows({ active }: { readonly active: boolean }) {
  const { t } = useTranslation();
  const statusQuery = useQuery({
    queryKey: hostStatusQueryKey,
    queryFn: getHostStatus,
    enabled: active,
    staleTime: 10_000,
  });
  const rows = aboutGatewayRows(statusQuery.data?.listen, statusQuery.data?.publicUrl);
  if (!active || rows.publicUrl === null) return null;

  return (
    <>
      {rows.statuslineCommand !== null ? (
        <SettingsRow
          id="setting-statusline-remote"
          title="settings:advanced_statuslineRemote"
          description="settings:advanced_statuslineRemoteDescription"
          status={
            <span className="block break-all font-mono text-ui-sm text-foreground">
              {rows.statuslineCommand}
            </span>
          }
          control={
            <CopyTextButton
              text={rows.statuslineCommand}
              label={t("settings:advanced_copyStatusline")}
            />
          }
        />
      ) : null}
      {rows.showPublicAddress && rows.publicUrl !== null ? (
        <SettingsRow
          id="setting-public-address"
          title="settings:advanced_publicAddress"
          description="settings:advanced_publicAddressDescription"
          status={
            <span className="block break-all font-mono text-ui-sm text-foreground">
              {rows.publicUrl}
            </span>
          }
          control={
            <CopyTextButton
              text={rows.publicUrl}
              label={t("settings:advanced_copyPublicAddress")}
            />
          }
        />
      ) : null}
    </>
  );
}

/**
 * myna's Settings › Uninstall (gui/uninstall.go): agents are put back, opening
 * at login is turned off, and the data folder is deleted once the app quits.
 * The desktop shell does the work; a plain browser has nothing to uninstall.
 */
export function AboutUninstallRow({ active }: { readonly active: boolean }) {
  const { t } = useTranslation();
  const statusQuery = useQuery({
    queryKey: hostStatusQueryKey,
    queryFn: getHostStatus,
    enabled: active && desktopShellAvailable(),
    staleTime: 10_000,
  });
  const [busy, setBusy] = useState(false);

  const uninstall = useCallback(async () => {
    const dataPath = statusQuery.data?.home ?? t("settings:advanced_uninstallDataFolder");
    let confirmed = false;
    try {
      confirmed = await ensureNativeApi().dialogs.confirm(
        [
          t("settings:advanced_uninstallConfirmTitle"),
          t("settings:advanced_uninstallConfirmMessage", { path: dataPath }),
        ].join("\n"),
        { confirmLabel: t("settings:advanced_uninstall"), destructive: true },
      );
    } catch {
      confirmed = false;
    }
    if (!confirmed) return;

    setBusy(true);
    try {
      await invokeDesktopShellCommand("desktop_uninstall");
    } catch (error) {
      toastManager.add({
        type: "error",
        title: t("settings:advanced_uninstallFailed"),
        description: messageOf(error),
      });
    } finally {
      setBusy(false);
    }
  }, [statusQuery.data?.home, t]);

  if (!active || !desktopShellAvailable()) return null;

  return (
    <SettingsRow
      id="setting-uninstall"
      title="settings:advanced_uninstall"
      description="settings:advanced_uninstallDescription"
      control={
        <Button
          size="xs"
          variant="destructive-outline"
          disabled={busy}
          onClick={() => void uninstall()}
        >
          {t("settings:advanced_uninstall")}
        </Button>
      }
    />
  );
}
