const NEOX_ISSUES_URL = "https://github.com/istoo/neox/issues/new/choose";

function messageOf(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

/**
 * myna's Settings › About › Open-source licenses: the notices every build
 * carries, generated by scripts/generate-third-party-notices.mjs. The bridge
 * serves the same text `neolix licenses` prints.
 */
export function AboutThirdPartyLicensesRow({ active }: { readonly active: boolean }) {
  const { t } = useTranslation();
  const [open, setOpen] = useState(false);
  const [notices, setNotices] = useState<string | null>(null);
  const [failed, setFailed] = useState(false);

  useEffect(() => {
    if (!open || notices !== null) return;
    let disposed = false;
    getThirdPartyNotices()
      .then((result) => {
        if (!disposed) setNotices(result.notices);
        return undefined;
      })
      .catch(() => {
        if (!disposed) setFailed(true);
      });
    return () => {
      disposed = true;
    };
  }, [notices, open]);

  if (!active) return null;

  return (
    <>
      <SettingsRow
        id="setting-third-party-licenses"
        title="settings:advanced_thirdPartyLicenses"
        description="settings:advanced_thirdPartyLicensesDescription"
        control={
          <Button size="xs" variant="outline" onClick={() => setOpen(true)}>
            {t("settings:host_reveal")}
          </Button>
        }
      />
      <Dialog open={open} onOpenChange={setOpen}>
        <DialogPopup className="max-w-2xl gap-0 p-0">
          <DialogHeader className="gap-1 p-4 pr-12">
            <DialogTitle className="text-base">
              {t("settings:advanced_thirdPartyLicenses")}
            </DialogTitle>
            <DialogDescription className="text-ui leading-snug">
              {t("settings:advanced_thirdPartyLicensesDescription")}
            </DialogDescription>
          </DialogHeader>
          <DialogPanel className="max-h-[min(62vh,520px)] px-4 py-3">
            {failed ? (
              <p className="text-ui text-destructive">{t("settings:advanced_licensesFailed")}</p>
            ) : notices === null ? (
              <p className="text-ui text-muted-foreground">
                {t("settings:advanced_licensesLoading")}
              </p>
            ) : (
              <pre className="whitespace-pre-wrap break-words font-mono text-ui-sm leading-relaxed text-foreground">
                {notices}
              </pre>
            )}
          </DialogPanel>
          <DialogFooter>
            <Button size="sm" onClick={() => setOpen(false)}>
              {t("common:app_close")}
            </Button>
          </DialogFooter>
        </DialogPopup>
      </Dialog>
    </>
  );
}

